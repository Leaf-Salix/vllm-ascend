                e6_3_hi = pl.tile.add(e6_2_hi, e5_3_lo)
                e6_3_v = pl.tile.sub(e6_3_hi, e6_2_hi)
                e6_3_lo = pl.tile.add(pl.tile.sub(e6_2_hi, pl.tile.sub(e6_3_hi, e6_3_v)), pl.tile.sub(e5_3_lo, e6_3_v))
